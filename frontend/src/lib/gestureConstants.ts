/**
 * 指挥手势解析的全部可调参数。
 *
 * 集中在这里是为了调手感时只改这一个文件，不必翻动逻辑代码。每个值都写了取这个数
 * 的理由 —— 大多来自「原实现哪里不对」或者指挥手势识别文献里的经验区间，改之前先
 * 看一眼理由，别把它们当成随手拍的魔法数字。
 *
 * 相关取值依据：
 *   - 拍点(ictus)取运动学拐点而非绝对幅度阈值：MIT《Inside the Conductor's Jacket》(TR-518)
 *   - 门限跟随近期信号包络动态重算（触发取包络 30%~50%）：自适应阈值文献
 *   - 手势幅度到音量的单调映射：Borchers《Personal Orchestra》(UIST 2002)
 *   - 停手后走 release 自然衰减而非瞬时切断：Friberg《Home Conducting》
 */

// ---- 时间窗口 ----
// 一律按毫秒，不按帧数。原实现用帧数（historySize=60、趋势取 30 帧）隐含 60Hz 假设，
// 而电脑模式下采样经 WebSocket 到达，网络抖动会让同样帧数覆盖忽长忽短的真实时间。

/** 历史保留时长。原为 60 帧 @60Hz ≈ 1000ms，取整到 1200ms 留些余量。 */
export const HISTORY_MS = 1200;
/** 趋势/密度判定窗口。原为 30 帧 @60Hz ≈ 500ms。 */
export const TREND_MS = 500;

// ---- 重力基线 ----
/**
 * 静止基线的跟踪时间常数。
 *
 * 原实现直接写死 energy = |加速度| - 9.81，等于假定拿到的一定是含重力的读数。但
 * sensor.ts 取值时是 `e.accelerationIncludingGravity || e.acceleration` —— 在
 * accelerationIncludingGravity 为空的设备上会退到不含重力的读数，此时基线是 0 而不是
 * 9.81，减完恒为负、clamp 成 0，那种设备上从头到尾一点声音都不会有，同时 cutoff
 * 疯狂误触发。改成慢速跟踪实际静止值，两种约定都能自己对上，也顺带吸收传感器零漂。
 *
 * 2 秒对应 0.08Hz 截止频率，远低于挥拍基频（约 1~3Hz），不会把动作本身滤掉。
 */
export const BASELINE_TAU_MS = 2000;

// ---- 力度包络与滞回 ----
/**
 * 力度取「最近这段时间里挥得最猛的那一下」，窗口长度即此值。
 *
 * 力度必须取自某种包络而不是瞬时能量：挥拍时能量在一拍之内必然从峰值掉到零，
 * 直接拿瞬时值当力度会让所有音轨跟着拍子整体脉动 —— 那正是「指挥时乐器乱响」。
 * 力度该反映「使多大劲」这个慢变量，逐拍的重音交给节奏声部去表现。
 *
 * 用滑动窗口取最大值，而不是指数衰减的峰值跟随器：后者在两个拍点之间会自然衰减
 * （600ms 时间常数遇上 500ms 一拍，每拍要掉到 0.435 倍），力度仍然是锯齿状的。
 * 滑动窗口只要盖得住一拍，稳定挥拍时窗口内的峰值就是恒定的，力度才真正平。
 * 1200ms 盖得住 50bpm 以上的所有常用速度。
 */
export const ACTIVITY_WINDOW_MS = 1200;
/**
 * 窗口峰值再做一次平滑的时间常数。
 *
 * 滑动窗口最大值在幅度变小时是阶跃下降的（要等旧的大值滑出窗口），直接用会有断崖。
 * 250ms 足以把这个台阶抹成滑坡，又不至于让力度反应迟钝。
 */
export const ACTIVITY_SMOOTH_TAU_MS = 250;
/**
 * 长期参考包络的释放时间常数，只用来定自适应门限（判断「还在不在指挥」），不参与
 * 力度取值。够覆盖一个乐句，又不会「记住」太久之前的一次大力挥动。
 */
export const ENV_TAU_MS = 1100;
/** 包络下限。防止长时间不动后包络趋近 0，导致一个极小的动作被误判成还在指挥。 */
export const ENV_FLOOR = 2.0;
/** 触发阈值 = 参考包络 * 该比例。文献建议 30%~50%，取下沿优先保证不误关。 */
export const ACTIVATE_RATIO = 0.3;
/** 关闭阈值 = 参考包络 * 该比例。与 ACTIVATE_RATIO 之间形成滞回带，避免临界值反复横跳。 */
export const DEACTIVATE_RATIO = 0.12;
/**
 * 力度的绝对映射区间，作用在「相对静止基线的能量偏离量」上。实测手持挥拍：中等
 * 幅度峰值约 3~5，大幅度 8~12。原实现用的 MAX=15 要靠剧烈甩动才够得到，这是
 * 「动作稍微小一点就没有声音」最直接的原因。
 *
 * 门限做自适应（适应每个人挥多大），力度取值保持绝对 —— 否则轻挥会被自动增益拉回
 * 满音量，强弱对比就没了，那是音乐上错误的。
 */
export const DYN_REST = 0.3;
export const DYN_FULL = 7.0;
/** 进入 active 后至少保持这么久才允许关闭。低于此的变化基本是传感器噪声和手抖。 */
export const MIN_ACTIVE_MS = 150;
/**
 * 连续安静多久算「真的停了」。
 *
 * 光靠 activity 衰减到门限以下来判停要 2 秒多 —— activity 的时间常数是为了跨过拍与拍
 * 之间的波谷才设的，不该同时用来决定停没停。这里直接看「连续安静了多久」：500ms 长于
 * 常用速度下的波谷时长（120bpm 约 200ms，60bpm 约 400ms），又能让停手后一秒左右
 * 就落到保持音量。
 */
export const QUIET_HOLD_MS = 500;
/**
 * 判断「设备在不在动」的短窗口与峰峰值门槛。
 *
 * 直接看原始模长在窗口内的波动范围，不经过重力基线 —— 基线是个 2 秒时间常数的慢变量，
 * 拿它判停会平白多等一两秒。静止时只剩传感器噪声，峰峰值通常远低于 0.8 m/s²；
 * 任何真实挥动都会远超这个值。含不含重力都成立。
 */
export const STILL_WINDOW_MS = 300;
export const STILL_PEAK_TO_PEAK = 0.8;
/** active 状态下的音量地板，保证「还在挥」的时候不会被瞬时低能量拽到近乎无声。 */
export const ACTIVE_FLOOR = 0.25;
/** 停手后衰减到的保持音量。不归零 —— 乐队继续轻声演奏，重新挥动立刻回来。 */
export const SUSTAIN_FLOOR = 0.18;
/** 停手后从当前音量衰减到 SUSTAIN_FLOOR 所需时长。 */
export const RELEASE_MS = 500;

// ---- cutoff（收势）判定 ----
/** 低能量需连续保持这么久才算真收势。低于人最快的有意手势变化周期（100~150ms）。 */
export const CUTOFF_HOLD_MS = 80;
/** 不应期，防止同一次收势被反复识别。对应收势后自然的呼吸间隔。 */
export const CUTOFF_REFRACTORY_MS = 500;

// ---- 拍点 ----
export const MIN_BEAT_INTERVAL_MS = 200; // 300 BPM
export const MAX_BEAT_INTERVAL_MS = 2000; // 30 BPM
/**
 * 拍点脉冲的衰减时间常数，**按当前速度算出来**，不再是一个定值。
 *
 * 原来固定 200ms。问题在慢速：88BPM 一拍 682ms，脉冲到下一拍前已经衰减到 0.03，
 * 等于每一拍走完一个完整的锯齿 —— 听感就是「打一拍猛地一响，然后一路沉下去，
 * 下一拍又猛地一响」。速度越慢，沉得越久。
 *
 * 现在拿**预测的拍长**（由检测到的 BPM 推出来）去定衰减：一拍多长，脉冲就按比例
 * 衰多快。这样重音的形状在任何速度下都一样，不会在慢速时提前塌到底。
 *
 * 0.4 倍拍长：重音在一拍的前 40% 里落下去，后面保持在地板上等下一拍。
 * 上下界防两头失控 —— 极快时别短到听不出起落，极慢时别长到糊成一片。
 */
export const PULSE_TAU_RATIO = 0.4;
export const PULSE_TAU_MIN_MS = 120;
export const PULSE_TAU_MAX_MS = 400;

/** 由当前速度推出脉冲的衰减常数。bpm 无效时退回中庸速度的取值。 */
export function pulseTauMs(bpm: number): number {
  if (!(bpm > 0)) return 200;
  const beatMs = 60000 / bpm;
  return Math.min(PULSE_TAU_MAX_MS, Math.max(PULSE_TAU_MIN_MS, beatMs * PULSE_TAU_RATIO));
}

/**
 * 两拍之间，节奏声部保底还剩多少（0 = 完全靠脉冲撑，1 = 完全不受脉冲影响）。
 *
 * **这是「指挥时每拍音量忽大忽小」的正主。** 原来节奏声部的激活度直接就是
 * `lift(beatPulse)`，脉冲一衰减，整条轨就从满音量掉到底噪，实测每拍摆动 6.3dB。
 * 而节奏轨本身放的是定音鼓写好的谱子，它自己就有节奏；再用用户的拍点去开关它，
 * 等于把第二套节奏叠在上面，而且两套并不同步（音乐走自己的网格，用户的拍点会飘）。
 *
 * 改成脉冲只做**重音**：地板抬到 0.45，摆幅收到约 2.4dB。听得出每一拍被强调了，
 * 不会听成音量在泵。想让打击乐更跳就调低这个数，代价是泵动感回来。
 */
export const RHYTHM_FLOOR = 0.45;

// ---- 声部混音（混音平衡范式）----
/**
 * 强调满量程对应的倾斜角度。
 *
 * 原实现是 sigmoid((-gamma-20)/15)，要把主旋律推到接近 1 得左倾 50° 以上，而手机
 * 端正握持时四个声部全都只有 0.21~0.27 —— 正常姿势下每个声部都只有约四分之一音量。
 * 现在倾 35° 即到满强调，端正时各声部一律回到 BED_LEVEL。
 */
export const EMPH_SPAN = 35;
/**
 * 未被强调的声部保留的音量比例。
 *
 * 混音平衡范式：所有声部始终在演奏，手势只调整「谁更突出」。被弱化的声部退到背景
 * 但仍清晰可闻，绝不静音 —— 声部忽有忽无正是「乐器乱响」的来源。
 */
export const BED_LEVEL = 0.45;
/** density 对底噪的调制幅度：动作越大底噪压得越低，强调对比越强烈。 */
export const CONTRAST_RANGE = 0.15;

// ---- 音频写入 ----
/**
 * 音量趋近的时间常数（秒）。约 150ms 到达目标值的 95%。
 *
 * 音量不能用 linearRampToValueAtTime：指挥时每帧（约 16ms，电脑模式下是 WebSocket
 * 到达节奏）都会写一次音量，而 ramp 时长若是 50ms，新调用总是在打断还没走完的旧 ramp，
 * 每次都从「当前实际值」重起一条斜率不同的新斜坡，听感就是抖动和咔哒声。
 * setTargetAtTime 是渐近逼近，新调用只是改目标值，曲线连续可导。取值比每帧间隔长，
 * 形成天然低通平滑，同时仍然跟手。
 *
 * 0.03 → 0.05：30ms 的时间常数比摄像头一帧（30fps 时 33ms）还短，等于每帧都追平了
 * 那一帧的目标值，关键点抖动原样进了音量。这里放长到跨得过两三帧，抖动才被真正低通掉。
 * 别再往上加：节奏声部的音量跟着 beatPulse 走，时间常数长过一拍的几分之一，
 * 重音就糊了（152BPM 一拍 395ms，当前的 150ms 还留得住轮廓）。
 */
export const VOLUME_TIME_CONSTANT = 0.05;

/**
 * 单轨音量的响度曲线指数。写进增益前先做 `gain ** GAMMA`。
 *
 * 实测（《埃格蒙特》尾声 14 声部，见 M7p3 的记录）：正常指挥时整体只有 −23 dBFS RMS，
 * 而**最响的现实情况已经到 −1.9 dBFS** —— 余量只剩 1.9 dB。所以「太小声」不是总音量
 * 开小了，是最大值和典型值之间拉开了 21 dB：`activation × dynamics` 是两个小数相乘，
 * 两个都在 0.5 附近时结果就只有 0.25，而人耳听到的是 −12 dB。
 *
 * 直接调大总音量会把那 1.9 dB 的余量吃穿（和声声部推满时就削波）。指数曲线只抬中间：
 * `x ** 0.65` 在 x=1 处仍然是 1，**顶不动**，而 0.29 抬到 0.44（+3.6 dB）、
 * 0.175 抬到 0.32（+5.2 dB）。代价是力度动态从 21 dB 压到约 15 dB —— 对一件手势乐器
 * 仍然够用，而 0.65 是留给「拍型大小 = 力度」这条教学主线的下限，再小就听不出强弱了。
 *
 * **还有一笔账要记在这里：它同时把节奏声部的重音压平了。** `rhythm` 的激活度是
 * `lift(beatPulse)`，而 beatPulse 是拍点瞬间跳到 1、之后按 pulseTauMs 衰减的
 * **点状量**；指数曲线抬低值比抬高值多，等于把那个台阶削矮了。152BPM、中等力度下
 * 实测：拍点/拍末的对比从 6.7 dB 降到 4.4 dB。之所以仍然接受，是因为定音鼓在实际
 * 混音里本来就比别的声部低 20 dB（那是渲染侧的电平问题，不是这里能治的），
 * gamma 反而让它整体响了 2.4 dB —— 更响，但没那么有劲。
 * **想再动 gamma 或 VOLUME_TIME_CONSTANT 之前，先把这两条一起算。**
 */
export const VOLUME_GAMMA = 0.65;
