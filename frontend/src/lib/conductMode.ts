/**
 * 用什么设备打拍子。
 *
 * ## 为什么这个选择不在「输出」页上
 *
 * 原来它是指挥台正上方的一条三选一切换。那是最显眼的位置，而它是个**装好就不会
 * 再动**的选择 —— 有摄像头的人永远用摄像头，拿手机当指挥棒的人永远用手机。
 * 一次性的配置不该常年占着指挥台的正中间，所以搬进「设置」。
 *
 * ## 为什么没有「单机模式」了
 *
 * 单机 = 用手机打开输出页，手机自己采手势、自己出声。它和电脑模式做的是同一件事，
 * 差别只在声音从哪儿出来 —— 而手机扬声器放十四轨管弦乐，本来就不是这个软件
 * 该有的样子。扫码接进电脑（电脑模式）能做到它能做的一切，声音还是从音箱出来的。
 */
